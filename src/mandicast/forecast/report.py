"""Render the evaluation tables from the stored JSON results (no hand-typed numbers).

    python -m mandicast.forecast.report

Reads experiments/forecast/dev/_reports/*.json, frozen_choices.json and holdout/_reports/final.json (if present)
and writes experiments/forecast/EVALUATION_TABLES.md.
"""

from __future__ import annotations

import json
import sys

from mandicast.config import get_settings
from mandicast.forecast.run import FROZEN, OUT

PCT = {"wape", "smape", "mape", "dir_acc_all", "dir_acc_moves_ge_2pct", "share_moves_ge_2pct", "coverage80",
       "coverage90", "rel_width80", "rel_width90"}


def fmt(k: str, v) -> str:
    if v is None:
        return "–"
    if isinstance(v, float):
        return f"{100 * v:.1f}%" if k in PCT else f"{v:.3f}"
    return f"{v:,}" if isinstance(v, int) else str(v)


def table(rows: list[dict], cols: list[str], header: list[str] | None = None) -> list[str]:
    out = ["| " + " | ".join(header or cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(fmt(c, r.get(c)) for c in cols) + " |" for r in rows]
    return out


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    lines = ["# MandiCast forecasting: evaluation tables", "",
             "Generated by `python -m mandicast.forecast.report` from the stored results. Percentages are of the",
             "actual price (WAPE, sMAPE) or of points (accuracy, coverage). Headline metrics exclude targets flagged",
             "`local_outlier` (methodology C5); the hold-out section also shows them included.", ""]
    commodities = get_settings().commodities
    lines += ["## 1. Development period (2023-01 … 2025-11): model choice", ""]
    for c in commodities:
        p = OUT / "dev" / "_reports" / f"{c.lower()}.json"
        if not p.exists():
            continue
        rep = json.loads(p.read_text(encoding="utf-8"))
        lines += [f"### {c}", "", f"Scored points: {rep['points']['common_points']:,} (targets "
                  f"{rep['points']['targets']:,}; outlier targets {rep['points']['outlier_targets']:,}).", ""]
        lines += table(sorted(rep["headline"], key=lambda r: (r["h"], r["wape"])),
                       ["h", "model", "n", "wape", "mase_vs_last_value", "smape", "dir_acc_moves_ge_2pct"],
                       ["h", "model", "points", "WAPE", "MASE vs last value", "sMAPE", "direction (moves ≥ 2%)"])
        if "selection" in rep:
            lines += ["", "Selection (mean of quarterly WAPE; must beat last value in ≥ 60% of quarters):", ""]
            lines += table(rep["selection"], ["h", "model", "mean_fold_wape", "share_folds_beating_last_value",
                                              "qualifies", "is_selected"],
                           ["h", "model", "mean quarterly WAPE", "quarters beating last value", "qualifies",
                            "selected"])
        lines.append("")
    if FROZEN.exists():
        fz = json.loads(FROZEN.read_text(encoding="utf-8"))
        lines += ["## 2. Frozen choices", "",
                  f"Frozen at {fz['frozen_at']} (code SHA-256 `{fz['code_sha256'][:16]}…`).", ""]
        rows = [{"commodity": c, "days 1–7": v["served"]["days_1_7"], "days 8–14": v["served"]["days_8_14"],
                 "intervals": v["intervals"]["method"],
                 "worst tercile deviation": v["intervals"]["worst_tercile_deviation"]}
                for c, v in fz["commodities"].items()]
        lines += table(rows, ["commodity", "days 1–7", "days 8–14", "intervals", "worst tercile deviation"])
        lines.append("")
    final = OUT / "holdout" / "_reports" / "final.json"
    if final.exists():
        fin = json.loads(final.read_text(encoding="utf-8"))
        lines += ["## 3. Hold-out (2025-12 … 2026-11), scored once", "",
                  f"Evaluated {fin['evaluated_at']}; code changed after freezing: "
                  f"**{fin['code_changed_after_freeze']}**.", ""]
        for c, v in fin["commodities"].items():
            s = v["served"]
            lines += [f"### {c}: served {s['served_models']['days_1_7']} (days 1–7) / "
                      f"{s['served_models']['days_8_14']} (days 8–14), intervals {s['interval_method']}", ""]
            rows = ([{**r, "forecast": "served"} for r in s["headline_h7_h14"]]
                    + [{**r, "forecast": "last value"} for r in s["last_value_h7_h14"]])
            lines += table(rows, ["forecast", "h", "n", "wape", "mase_vs_last_value", "dir_acc_moves_ge_2pct",
                                  "coverage80", "coverage90", "rel_width80"],
                           ["forecast", "h", "points", "WAPE", "MASE", "direction (moves ≥ 2%)", "80% coverage",
                            "90% coverage", "80% width"])
            lines += ["", "Including outlier-flagged targets:", ""]
            lines += table(s["headline_including_outlier_targets"], ["h", "n", "wape", "mase_vs_last_value"],
                           ["h", "points", "WAPE", "MASE"])
            lines += ["", "All models on the same hold-out points (outliers excluded):", ""]
            lines += table(sorted(v["all_models_headline"], key=lambda r: (r["h"], r["wape"])),
                           ["h", "model", "wape", "mase_vs_last_value", "dir_acc_moves_ge_2pct"],
                           ["h", "model", "WAPE", "MASE", "direction (moves ≥ 2%)"])
            lines.append("")
    path = OUT / "EVALUATION_TABLES.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("written:", path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
