"""Column reference of every table, generated from the database (docs/05 §5).

    python -m mandicast.db.schema_doc            # rewrite the generated section of docs/05 from DATABASE_URL

`tests/test_docs.py` renders the same section from the test database (built from the migrations) and fails when the
committed document differs, so the reference cannot drift from the schema.
"""

from __future__ import annotations

import re
import sys

from sqlalchemy import Connection, create_engine, text

from mandicast.config import PROJECT_ROOT, get_settings

DOC = PROJECT_ROOT / "docs" / "05_data_dictionary.md"
BEGIN, END = "<!-- schema:begin (generated by python -m mandicast.db.schema_doc) -->", "<!-- schema:end -->"

_COLUMNS = text("""
    SELECT c.table_name, c.column_name, c.is_nullable, c.column_default,
           format_type(a.atttypid, a.atttypmod) AS type
    FROM information_schema.columns c
    JOIN pg_attribute a ON a.attrelid = format('%I.%I', c.table_schema, c.table_name)::regclass
                       AND a.attname = c.column_name
    WHERE c.table_schema = 'public' AND c.table_name <> 'alembic_version'
    ORDER BY c.table_name, c.ordinal_position""")


def _default(value: str | None) -> str:
    if value is None:
        return ""
    if value.startswith("nextval("):
        return "serial"
    return re.sub(r"::[a-z ]+(\[\])?", "", value)  # drop casts: 'en'::text -> 'en'


def render(conn: Connection) -> str:
    rows = conn.execute(_COLUMNS).all()
    lines = [BEGIN, ""]
    current = None
    for table, column, nullable, default, type_ in rows:
        if table != current:
            if current is not None:
                lines.append("")
            lines += [f"**`{table}`**", "", "| Column | Type | Null | Default |", "|---|---|---|---|"]
            current = table
        null = "" if nullable == "NO" else "yes"
        lines.append(f"| `{column}` | {type_} | {null} | {_default(default).replace('|', '\\|')} |")
    lines += ["", END]
    return "\n".join(lines)


def committed() -> str:
    doc = DOC.read_text(encoding="utf-8")
    start, end = doc.find(BEGIN), doc.find(END)
    if start < 0 or end < 0:
        raise ValueError(f"{DOC.name} has no generated schema section")
    return doc[start:end + len(END)]


def main() -> int:
    engine = create_engine(get_settings().database_url.get_secret_value())
    with engine.connect() as conn:
        section = render(conn)
    doc = DOC.read_text(encoding="utf-8")
    DOC.write_text(doc.replace(committed(), section), encoding="utf-8", newline="\n")
    print(f"{DOC.relative_to(PROJECT_ROOT)}: {section.count(chr(10) + '| `')} columns")
    return 0


if __name__ == "__main__":
    sys.exit(main())
