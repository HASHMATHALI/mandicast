// Regenerates the API types from the running MandiCast API's own OpenAPI document.
//   npm run gen:api            (API at http://127.0.0.1:8000, or set MANDICAST_API)
// Writes src/api/openapi.json (the snapshot the tests compare against) and src/api/schema.d.ts.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const base = process.env.MANDICAST_API ?? "http://127.0.0.1:8000";
const res = await fetch(`${base}/openapi.json`, { signal: AbortSignal.timeout(10_000) });
if (!res.ok) throw new Error(`GET ${base}/openapi.json -> HTTP ${res.status}`);
const doc = await res.json();
const here = (p) => fileURLToPath(new URL(p, import.meta.url));
writeFileSync(here("../src/api/openapi.json"), JSON.stringify(doc, null, 2) + "\n");
const ast = await openapiTS(doc);
const header = "// Generated by scripts/gen-api.mjs from the API's /openapi.json. Do not edit by hand.\n";
writeFileSync(here("../src/api/schema.d.ts"), header + astToString(ast));
console.log(`API ${doc.info.title} ${doc.info.version}: ${Object.keys(doc.paths).length} paths, ` +
  `${Object.keys(doc.components?.schemas ?? {}).length} schemas`);
