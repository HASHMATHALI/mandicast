"""Render the Phase 5 result tables from reports/phase5/*.json (no hand-typed numbers).

    python -I scripts/phase5_tables.py      → reports/phase5/PHASE5_TABLES.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "reports" / "phase5"


def pct(x) -> str:
    return "–" if x is None else f"{100 * x:.2f}%"


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    lines = ["# Phase 5 tables (generated by `scripts/phase5_tables.py`)", ""]
    g = D / "gate_backtest.json"
    if g.exists():
        gb = json.loads(g.read_text(encoding="utf-8"))
        lines += ["## Promotion gate backtest (C10b), real data", "",
                  f"Run {gb['run_at']}. WAPE on each candidate's early-stopping set (optimistic for the candidate).", "",
                  "| Crop | Quarter start | Best iteration | Points | Candidate | Last value | Production (previous quarter) "
                  "| Gate as first recorded | Gate as amended (iii not blocking: previous model cannot serve) |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for c, v in gb["commodities"].items():
            for r in v["quarters"]:
                lines.append(f"| {c} | {r['quarter_start']} | {r['best_iteration']} | {r['points']:,} | "
                             f"{pct(r['wape_candidate'])} | {pct(r['wape_last_value'])} | {pct(r['wape_production'])} | "
                             f"{'passed' if r['passed'] else 'rejected: ' + '; '.join(r['failed'])} | "
                             f"{'passed' if all(x.startswith('(iii)') for x in r['failed']) else 'rejected'} |")
        lines += ["", "Deliberately worse candidates at 2026-10-01 (must be rejected):", "",
                  "| Crop | Candidate | WAPE | Last value | Production | Gate | Failed rules |", "|---|---|---|---|---|---|---|"]
        for c, v in gb["commodities"].items():
            for name, r in v["deliberately_worse_at_2026_10_01"].items():
                lines.append(f"| {c} | {name} | {pct(r['wape_candidate'])} | {pct(r['wape_last_value'])} | "
                             f"{pct(r['wape_production'])} | {'passed' if r['passed'] else 'rejected'} | "
                             f"{'; '.join(x.split(' ')[0] for x in r['failed'])} |")
        lines.append("")
    f = D / "fallback_backtest.json"
    if f.exists():
        fb = json.loads(f.read_text(encoding="utf-8"))
        lines += ["## Fallback rule simulation (C10c) on walk-forward predictions", "",
                  f"Run {fb['run_at']}. Window {fb['window_days']} days, at least {fb['min_points']} points. Outlier "
                  "targets excluded.", "",
                  "| Crop | Period | Days | Points | Model only | Last value only | Served (rule) | Origins on fallback |",
                  "|---|---|---|---|---|---|---|---|"]
        for c, rows in fb["commodities"].items():
            for r in rows:
                lines.append(f"| {c} | {r['period']} | {r['days']} | {r['points']:,} | {pct(r['wape_model'])} | "
                             f"{pct(r['wape_last_value'])} | {pct(r['wape_served'])} | "
                             f"{r['origins_on_fallback']} / {r['origins']} |")
        lines.append("")
    out = D / "PHASE5_TABLES.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("written", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
