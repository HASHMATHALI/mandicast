"""Build reports/profile/PROFILE_SUMMARY.md from the per-commodity profile JSONs and eligibility.json.

    .venv/Scripts/python -I scripts/profile_summary.py

Every number in the summary is copied by code from those files, so the document cannot drift from the data.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROFILE = ROOT / "reports" / "profile"


def fmt(n) -> str:
    return f"{n:,}" if isinstance(n, int) else str(n)


def main() -> None:
    profiles = {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in sorted(PROFILE.glob("*.json"))
                if p.stem != "eligibility"}
    elig_path = PROFILE / "eligibility.json"
    elig = json.loads(elig_path.read_text(encoding="utf-8")) if elig_path.exists() else {"commodities": {}}
    names = list(profiles)

    def row(label: str, f) -> str:
        return f"| {label} | " + " | ".join(fmt(f(profiles[c], elig["commodities"].get(c, {}))) for c in names) + " |"

    lines = [
        "# Profile summary: AGMARKNET daily prices (data.gov.in resource 35985678-…)",
        "",
        "Generated by `scripts/profile_summary.py` from `reports/profile/*.json`. Download date 2026-11-26.",
        "Series in the coverage rows = (commodity, mandi); eligibility rules: `docs/06_forecasting_methodology.md` §2.",
        "",
        "| Check | " + " | ".join(names) + " |",
        "|---|" + "---|" * len(names),
        row("Rows stored = API total", lambda p, e: f"{p['integrity']['rows_read']:,} / {p['integrity']['total_reported_max']:,}"),
        row("Pages failing SHA-256", lambda p, e: len(p["integrity"]["pages_failing_sha256"])),
        row("Boundary dates re-fetched", lambda p, e: p["integrity"].get("boundary_repair", {}).get("boundary_dates_replaced", 0)),
        row("Rows recovered by the re-fetch", lambda p, e: p["integrity"].get("boundary_repair", {}).get("refetched_rows_not_in_pages", "n/a")),
        row("Date range", lambda p, e: f"{p['dates']['min']} … {p['dates']['max']}"),
        row("Unparseable / future dates", lambda p, e: f"{p['dates']['unparseable']} / {p['dates']['after_download_date']}"),
        row("Commodity codes", lambda p, e: ", ".join(f"{x['Commodity_Code']} ({x['len']:,})" for x in p["names"]["commodity_name_code_pairs"])),
        row("Exact duplicate rows", lambda p, e: p["duplicates"]["exact_duplicate_rows"]),
        row("Same-day conflicting keys", lambda p, e: p["duplicates"]["keys_with_conflicting_modal"]),
        row("Min = max = 0 (only modal reported)", lambda p, e: p["prices"]["violations"].get("min_and_max_zero_modal_positive", "n/a")),
        row("Min > max", lambda p, e: p["prices"]["violations"]["min_gt_max"]),
        row("Modal outside [min, max]", lambda p, e: p["prices"]["violations"]["modal_lt_min"] + p["prices"]["violations"]["modal_gt_max"]),
        row("Non-numeric modal", lambda p, e: p["prices"]["Modal_Price"]["non_numeric"]),
        row("Modal p1 / p50 / p99 (₹/q)", lambda p, e: f"{p['prices']['modal_quantiles']['p1']:,.0f} / {p['prices']['modal_quantiles']['p50']:,.0f} / {p['prices']['modal_quantiles']['p99']:,.0f}"),
        row("Modal max (₹/q)", lambda p, e: f"{p['prices']['modal_quantiles']['max']:,.0f}"),
        row("Local outliers (>3× or <⅓ of 15-obs median)", lambda p, e: p["outliers"]["ratio_gt_3_or_lt_one_third"]),
        row("States / districts / mandis", lambda p, e: f"{len(p['names']['states'])} / {p['names']['n_districts']:,} / {p['names']['n_markets']:,}"),
        row("Market names with spelling variants", lambda p, e: p["names"]["market_spelling_variants"]["groups_with_multiple_spellings"]),
        row("Mandis reporting in last 14 days", lambda p, e: e.get("pass_recently_active", "n/a")),
        row("… and ≥ 250 report days in last 730", lambda p, e: e.get("pass_active_and_history", "n/a")),
        row("**Eligible mandis (all rules)**", lambda p, e: e.get("eligible_markets", "n/a")),
        row("States with an eligible mandi", lambda p, e: e.get("eligible_states", "n/a")),
        row("Mandi-days of history in eligible series", lambda p, e: e.get("eligible_market_days_all_history", "n/a")),
        row("History of eligible mandis, years (p10 / p50 / p90)",
            lambda p, e: " / ".join(str(x) for x in e.get("eligible_history_years_p10_p50_p90") or []) or "n/a"),
        row("Eligible mandis with ≥ 5 years of history", lambda p, e: e.get("eligible_with_5y_history", "n/a")),
        "",
        "Coverage and eligibility rows use canonical mandi names (`scripts/eligibility.py`): whitespace and case",
        "normalised, Keralam → Kerala, Uttrakhand → Uttarakhand, and the \" APMC\" suffix that AGMARKNET added to",
        "almost all market names on 1–4 Nov 2025 removed. The rows above them count source names as received.",
        "",
        f"Eligible (commodity, mandi) series in total: **{sum(elig['commodities'].get(c, {}).get('eligible_markets', 0) for c in names):,}**.",
        f"Total rows stored: **{sum(p['integrity']['rows_read'] for p in profiles.values()):,}**.",
        "",
    ]
    (PROFILE / "PROFILE_SUMMARY.md").write_text("\n".join(lines), encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
